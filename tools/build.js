// Validates every data file and writes data/manifest.js
// Usage: node tools/build.js
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, "..");
const ctx = {}; ctx.window = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "data/registry.js"), "utf8"), ctx);
const NS = ctx.NS;
const types = new Set(["p", "list", "table", "cards", "tip", "warn", "mnem", "flow", "cycle", "compare", "svg"]);
const manifest = {}; let errors = 0, totalQ = 0;
function err(where, msg) { errors++; console.log("✗ " + where + ": " + msg); }
for (const s of NS.subjects) {
  for (const u of s.theory.concat(s.practical)) {
    const f = path.join(root, "data", s.id, u.id + ".js");
    if (!fs.existsSync(f)) continue;
    try { vm.runInContext(fs.readFileSync(f, "utf8"), ctx, { filename: f }); }
    catch (e) { err(f, "syntax/runtime " + e.message); continue; }
    const d = NS.data[s.id] && NS.data[s.id][u.id];
    const w = s.id + "/" + u.id;
    if (!d) { err(w, "file did not register unit"); continue; }
    if (!Array.isArray(d.sections) || !d.sections.length) err(w, "no sections");
    (d.sections || []).forEach((sec, i) => {
      if (!sec.h || !sec.h.en || !sec.h.ar) err(w, "section " + i + " heading en/ar");
      (sec.b || []).forEach((b, j) => {
        const at = w + " s" + i + "b" + j + "(" + b.t + ")";
        if (!types.has(b.t)) err(at, "unknown block type");
        if (["p", "tip", "warn"].includes(b.t) && (!b.en || !b.ar)) err(at, "missing en/ar");
        if (b.t === "list" && (!Array.isArray(b.en) || !Array.isArray(b.ar))) err(at, "list en/ar arrays");
        if (b.t === "table") { if (!b.h || !b.r) err(at, "table h/r"); else b.r.forEach((r, k) => { if (r.length !== b.h.length) err(at, "row " + k + " has " + r.length + " cells, header " + b.h.length); }); if (b.ar) b.ar.r.forEach((r, k) => { if (r.length !== b.ar.h.length) err(at, "ar row " + k + " cell count"); }); }
        if ((b.t === "flow" || b.t === "cycle") && !(b.steps || []).every(x => x.en && x.ar)) err(at, "steps en/ar");
        if (b.t === "cards" && !(b.items || []).every(x => x.en && x.ar && x.i)) err(at, "cards need i/en/ar");
        if (b.t === "compare" && !(b.cols || []).every(c => c.h && c.en && c.ar)) err(at, "compare cols");
        if (b.t === "mnem" && !(b.rows || []).length) err(at, "mnem rows");
      });
    });
    const qs = d.questions || [];
    const seen = new Set();
    qs.forEach((q, i) => {
      const at = w + " Q" + (i + 1);
      const a = Array.isArray(q.a) ? q.a : [q.a];
      if (!q.q || !Array.isArray(q.o) || q.o.length < 4) err(at, "needs q and ≥4 options");
      if (!q.r || q.r.length < 25) err(at, "rationale missing/short");
      if (!a.length || a.some(k => typeof k !== "number" || k < 0 || k >= q.o.length)) err(at, "bad answer index");
      if (new Set(a).size !== a.length) err(at, "duplicate answer index");
      if (q.s && a.length < 2) err(at, "SATA with <2 answers");
      if (!q.s && a.length > 1) err(at, "multiple answers but not flagged SATA");
      if (new Set(q.o).size !== q.o.length) err(at, "duplicate options");
      const key = q.q.trim().toLowerCase(); if (seen.has(key)) err(at, "duplicate question"); seen.add(key);
      if (/all of the above|none of the above/i.test(q.o.join("|"))) err(at, "avoid all/none of the above");
    });
    // answer-position balance (single-answer)
    manifest[s.id] = manifest[s.id] || {};
    manifest[s.id][u.id] = { q: qs.length, s: d.sections.length, sata: qs.filter(q => q.s).length };
    totalQ += qs.length;
    console.log("✓ " + w + "  sections=" + d.sections.length + "  Qs=" + qs.length + "  SATA=" + qs.filter(q => q.s).length + "  priority=" + qs.filter(q => q.p).length);
  }
}
fs.writeFileSync(path.join(root, "data/manifest.js"),
  "/* generated by tools/build.js — do not edit */\nNS.version = \"" + Date.now().toString(36) + "\";\nNS.manifest = " + JSON.stringify(manifest) + ";\n");
console.log("\nTotal questions: " + totalQ + (errors ? "\n" + errors + " ERRORS" : "\nNo errors"));
process.exit(errors ? 1 : 0);
